#!/usr/bin/env bash
# Builds dist/ from app/: writes config.js from the session file and stamps the git sha into the page (R6).
# usage: ./build.sh [session-file]   (default ../.session)
set -euo pipefail
cd "$(dirname "$0")"
SESSION_FILE="${1:-../.session}"
if [ -n "$(git status --porcelain -- app build.sh wrangler.jsonc 2>/dev/null)" ]; then echo "working tree is dirty: commit first so the build sha names this code" >&2; exit 1; fi
SHA=$(git rev-parse HEAD)
rm -rf dist && mkdir -p dist && cp app/index.html app/app.js app/api.js app/style.css dist/
sed -i '' "s/__BUILD_SHA__/$SHA/g" dist/index.html
printf "// generated by build.sh at %s for build %s\nexport const API = 'https://hq.mega.dev/challenges/show-me-when/api';\nexport const SESSION = '%s';\n" "$(date -u +%FT%TZ)" "$SHA" "$(tr -d '\n' < "$SESSION_FILE")" > dist/config.js
printf '%s\n' "$SHA" > dist/BUILD
if [ -d proof ]; then mkdir -p dist/proof && find proof -maxdepth 1 -type f -name "*.webm" -exec cp {} dist/proof/ \; && echo "proof files: $(ls dist/proof | tr "\n" " ")"; fi
echo "built dist/ for $SHA"
